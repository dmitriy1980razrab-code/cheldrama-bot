"""Presentation groups for reports; questionnaire interests are not subscriptions."""
SECTIONS = (
    ('Аудитория','Количество профилей зрителей по каналам и состояниям на текущий момент.'),
    ('Интересы','Жанры, артисты и премьеры из анкеты. Это предпочтения, а не подписки на показы. Изменения — число добавлений/удалений отметок за период.'),
    ('Подписки на показы','Подписки и отписки относятся к конкретным показам. Показатели за период рассчитаны по последним датам записей подписок; они не означают число уникальных зрителей. Данные о покупке билетов пока не подключены.'),
    ('Реклама','Действующее рекламное согласие — число зрителей сейчас. Выдачи и отзывы согласия — события за период: один зритель может совершить несколько действий. Результаты рассылок относятся к доставкам.'),
    ('Согласия на уведомления','События согласий на обработку ПДн и сервисные уведомления. Это не рекламные согласия и не число уникальных зрителей.'),
    ('Обращения','Количество обращений по направлениям и среднее время первого ответа сотрудника в минутах.'),
)


def section_for(row):
    metric,group=row[:2]
    if metric in ('Приоритеты сейчас','Премьеры сейчас','Изменения предпочтений за период'):return 'Интересы'
    if metric.startswith(('Подписки на показы','Отписки от показов')):return 'Подписки на показы'
    if metric.startswith(('Рекламное согласие','Результаты кампаний','Отзыв рекламы')):return 'Реклама'
    if metric=='Согласия за период':return 'Реклама' if group=='Реклама' else 'Согласия на уведомления'
    if metric in ('Обращения за период','Первый ответ, минуты (среднее)'):return 'Обращения'
    return 'Аудитория'


def grouped_reports(rows):
    groups={name:[] for name,_ in SECTIONS}
    for row in rows:
        section=section_for(row)
        metric=row[0]
        if metric=='Согласия за период':metric='События согласий за период'
        elif metric=='Приоритеты сейчас':metric='Сохранённые интересы · зрителей сейчас'
        elif metric=='Премьеры сейчас':metric='Интересуются премьерами · зрителей сейчас'
        elif metric=='Рекламное согласие сейчас':metric='Реклама разрешена · зрителей сейчас'
        elif metric=='Профили сейчас':metric='Профили зрителей сейчас'
        groups[section].append((metric,*row[1:]))
    return [(name,note,groups[name]) for name,note in SECTIONS]


def headers_for(section):
    columns=['Показатель','Группа','Значение','За период / сейчас','Предыдущий период','Изменение']
    if section=='Интересы':
        columns[1]='Тип интереса / изменение'
        columns[2]='Жанр или артист'
    elif section=='Подписки на показы':
        columns[1]='Действие'
        columns[2]='Спектакль и показ'
    return columns
